    public static string Run(ProcessOptions opts)
    {
        var sb = new StringBuilder();
        int ok = 0;
        foreach (var (a, c, exp) in Cases)
        {
            var res = CodeProcessor.Process(a, c, opts);
            bool pass = res.Result == exp;
            if (pass) ok++;
            sb.AppendLine($"{(pass ? "OK  " : "FAIL")}  «{c}» -> «{res.Result}»" +
                          (pass ? "" : $"   (ожидалось «{exp}»)"));
        }
        sb.Insert(0, $"Пройдено {ok} из {Cases.Length}{Environment.NewLine}{Environment.NewLine}");
        return sb.ToString();
    }
